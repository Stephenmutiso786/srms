function app_generate_receipt_verification_code(PDO $conn): string
{
	for ($i = 0; $i < 12; $i++) {
		$code = 'RCV-' . date('Ymd') . '-' . strtoupper(substr(bin2hex(random_bytes(4)), 0, 8));
		$stmt = $conn->prepare("SELECT 1 FROM tbl_receipts WHERE verification_code = ? LIMIT 1");
		$stmt->execute([$code]);
		if (!$stmt->fetchColumn()) {
			return $code;
		}
	}
	return 'RCV-' . date('YmdHis');
}

function app_receipt_verify_url(string $verificationCode): string
{
	$verificationCode = trim($verificationCode);
	if ($verificationCode === '') {
		return '';
	}
	$scheme = (!empty($_SERVER['HTTPS']) && strtolower((string)$_SERVER['HTTPS']) !== 'off') ? 'https' : 'http';
	$host = trim((string)($_SERVER['HTTP_HOST'] ?? ''));
	if ($host === '') {
		return 'verify_receipt?code=' . urlencode($verificationCode);
	}
	$basePath = rtrim(str_replace('\\', '/', dirname((string)($_SERVER['SCRIPT_NAME'] ?? ''))), '/');
	return $scheme . '://' . $host . ($basePath !== '' ? $basePath : '') . '/verify_receipt?code=' . urlencode($verificationCode);
}

function app_generate_receipt_number(PDO $conn): string
{
	app_ensure_receipts_table($conn);
	$prefix = 'RCPT-' . date('Ymd') . '-';
	for ($i = 0; $i < 12; $i++) {
		$rand = (string)random_int(1000, 9999);
		$receiptNo = $prefix . $rand;
		$stmt = $conn->prepare("SELECT 1 FROM tbl_receipts WHERE receipt_number = ? LIMIT 1");
		$stmt->execute([$receiptNo]);
		if (!$stmt->fetchColumn()) {
			return $receiptNo;
		}
	}
	return $prefix . (string)time();
}

