function app_discipline_history_summary(PDO $conn, string $studentId): array
{
	$summary = ['total_cases' => 0, 'last_offense_date' => null, 'behavior_trend' => 'Stable', 'repeat_offender' => false];
	if ($studentId === '' || !app_table_exists($conn, 'tbl_discipline_cases')) {
		return $summary;
	}
	try {
		app_ensure_discipline_management_schema($conn);
		$stmt = $conn->prepare("SELECT COUNT(*) AS total_cases, MAX(COALESCE(date_reported, created_at)) AS last_offense_date
			FROM tbl_discipline_cases
			WHERE student_id = ?");
		$stmt->execute([$studentId]);
		$row = $stmt->fetch(PDO::FETCH_ASSOC) ?: [];
		$totalCases = (int)($row['total_cases'] ?? 0);
		$summary['total_cases'] = $totalCases;
		$summary['last_offense_date'] = $row['last_offense_date'] ?? null;
		$summary['repeat_offender'] = $totalCases >= 3;
		if ($totalCases >= 5) {
			$summary['behavior_trend'] = 'Worsening';
		} elseif ($totalCases >= 3) {
			$summary['behavior_trend'] = 'Needs Attention';
		} elseif ($totalCases <= 1) {
			$summary['behavior_trend'] = 'Improving';
		}
	} catch (Throwable $e) {
		error_log('[app_discipline_history_summary] ' . $e->getMessage());
	}
	return $summary;
}

