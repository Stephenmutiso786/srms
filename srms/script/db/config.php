function app_exam_teacher_can_reenter(PDO $conn, int $examId, int $subjectCombinationId, int $teacherId, ?string $examStatus = null): bool
{
	if ($examId < 1 || $subjectCombinationId < 1 || $teacherId < 1) {
		return false;
	}
	$currentStatus = $examStatus;
	if ($currentStatus === null) {
		try {
			$stmt = $conn->prepare("SELECT status FROM tbl_exams WHERE id = ? LIMIT 1");
			$stmt->execute([$examId]);
			$currentStatus = (string)$stmt->fetchColumn();
		} catch (Throwable $e) {
