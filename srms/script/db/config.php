function app_build_class_name(string $grade, string $stream = '', string $fallback = ''): string
{
	$grade = trim($grade);
	$stream = trim($stream);
	$fallback = trim($fallback);
	if ($grade === '' && $fallback !== '') {
		$canonicalFallback = app_cbe_canonical_class_name($fallback);
		return $canonicalFallback !== '' ? $canonicalFallback : ucfirst($fallback);
	}
	$canonicalGrade = app_cbe_canonical_class_name($grade);
	if ($canonicalGrade !== '') {
		$grade = $canonicalGrade;
	} elseif ($grade !== '') {
		$grade = ucfirst($grade);
	}
	if ($stream === '') {
		return $grade;
	}
	return trim($grade . ' ' . strtoupper($stream));
}

