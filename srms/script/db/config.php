function app_apply_mysql_patch(PDO $conn, string $path, string $migrationName): void
{
	if (DBDriver !== 'mysql' || !is_file($path)) {
		return;
	}

	if (!app_table_exists($conn, 'tbl_schema_migrations')) {
		$conn->exec("CREATE TABLE IF NOT EXISTS tbl_schema_migrations (
			id int NOT NULL AUTO_INCREMENT,
			name varchar(190) NOT NULL,
			applied_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
			PRIMARY KEY (id),
			UNIQUE KEY tbl_schema_migrations_name_uq (name)
		) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4");
	}

	$stmt = $conn->prepare("SELECT 1 FROM tbl_schema_migrations WHERE name = ? LIMIT 1");
	$stmt->execute([$migrationName]);
	if ($stmt->fetchColumn()) {
		return;
	}

	$sql = (string)file_get_contents($path);
	if ($sql === '') {
		return;
	}

	$sql = preg_replace('/^\s*--.*$/m', '', $sql);
	$parts = preg_split('/;\s*(?:\r?\n|$)/', (string)$sql) ?: [];

	try {
		foreach ($parts as $statement) {
			$statement = trim((string)$statement);
			if ($statement === '') {
				continue;
			}
			$conn->exec($statement);
		}
		$stmt = $conn->prepare("INSERT INTO tbl_schema_migrations (name) VALUES (?)");
		$stmt->execute([$migrationName]);
	} catch (Throwable $e) {
		throw $e;
	}
}

function app_ensure_current_mode_mysql_schema(PDO $conn): void
{
	static $done = false;
	if ($done || DBDriver !== 'mysql') {
		return;
	}

	$patchPath = app_mysql_current_mode_patch_path();
	if ($patchPath) {
