function app_sync_student_finance_class_links(PDO $conn, ?string $studentId = null): void
{
	if (!app_table_exists($conn, 'tbl_invoices') || !app_table_exists($conn, 'tbl_students')) {
		return;
	}

	if (DBDriver === 'pgsql') {
		$sql = "UPDATE tbl_invoices AS i
			SET class_id = s.class
			FROM tbl_students AS s
			WHERE s.id = i.student_id
			  AND i.status <> 'void'
			  AND s.class IS NOT NULL
			  AND (i.class_id IS NULL OR i.class_id <> s.class)";
	} else {
		$sql = "UPDATE tbl_invoices i
			JOIN tbl_students s ON s.id = i.student_id
			SET i.class_id = s.class
			WHERE i.status <> 'void'
			  AND s.class IS NOT NULL
			  AND (i.class_id IS NULL OR i.class_id <> s.class)";
	}
	$params = [];
	if ($studentId !== null && trim($studentId) !== '') {
		$sql .= " AND i.student_id = ?";
		$params[] = trim($studentId);
	}

	$stmt = $conn->prepare($sql);
	$stmt->execute($params);
}

