function app_cbe_rows_match_overall_default(array $rows): bool
{
	$rows = array_values($rows);
	$default = app_default_overall_grading_rows();
	if (count($rows) !== count($default)) {
		return false;
	}
	foreach ($default as $index => $expected) {
		$row = $rows[$index] ?? [];
		if (
			strtoupper(trim((string)($row['level'] ?? $row['grade'] ?? ''))) !== $expected['grade'] ||
			(float)($row['min_mark'] ?? $row['min'] ?? -1) !== (float)$expected['min'] ||
			(float)($row['max_mark'] ?? $row['max'] ?? -1) !== (float)$expected['max'] ||
			(int)($row['points'] ?? -1) !== (int)$expected['points']
		) {
			return false;
		}
	}
	return true;
}

function app_grading_rows_contain_legacy_labels(array $rows): bool
{
	foreach ($rows as $row) {
		$label = strtoupper(trim((string)($row['grade'] ?? $row['level'] ?? '')));
		if (in_array($label, ['A+', 'A', 'A-', 'B+', 'B', 'B-', 'C+', 'C', 'C-', 'D+', 'D', 'D-', 'E', 'F'], true)) {
			return true;
		}
	}
	return false;
}

function app_replace_grading_scales(PDO $conn, int $gradingSystemId, array $rows): void
{
	if ($gradingSystemId < 1 || !app_table_exists($conn, 'tbl_grading_scales')) {
		return;
	}

	$stmt = $conn->prepare("DELETE FROM tbl_grading_scales WHERE grading_system_id = ?");
	$stmt->execute([$gradingSystemId]);

	$stmt = $conn->prepare("INSERT INTO tbl_grading_scales (grading_system_id, min_score, max_score, grade, points, remark, sort_order, is_active) VALUES (?,?,?,?,?,?,?,?)");
	foreach ($rows as $row) {
		$stmt->execute([
			$gradingSystemId,
			(float)($row['min'] ?? 0),
			(float)($row['max'] ?? 0),
			(string)($row['grade'] ?? ''),
			(float)($row['points'] ?? 0),
			(string)($row['remark'] ?? ''),
			(int)($row['order'] ?? 0),
			(int)($row['active'] ?? 1),
		]);
	}
}

