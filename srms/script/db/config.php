function app_migrate_cbc_to_cbe_schema(PDO $conn): void
{
	static $done = false;
	if ($done) {
		return;
	}

	$tableRenames = [
		'tbl_cbc_assessments' => 'tbl_cbe_assessments',
		'tbl_cbc_grading' => 'tbl_cbe_grading',
		'tbl_cbc_mark_submissions' => 'tbl_cbe_mark_submissions',
		'tbl_cbc_strands' => 'tbl_cbe_strands',
		'tbl_cbc_competencies' => 'tbl_cbe_competencies',
	];

	foreach ($tableRenames as $oldTable => $newTable) {
		if (!app_table_exists($conn, $oldTable) || app_table_exists($conn, $newTable)) {
			continue;
		}

		try {
			if (DBDriver === 'pgsql') {
				$conn->exec("ALTER TABLE {$oldTable} RENAME TO {$newTable}");
			} else {
				$conn->exec("RENAME TABLE {$oldTable} TO {$newTable}");
			}
			app_forget_table_exists_cache($oldTable);
			app_forget_table_exists_cache($newTable);
		} catch (Throwable $e) {
			error_log('[app_migrate_cbc_to_cbe_schema.table] ' . $e->getMessage());
		}
	}

	if (app_table_exists($conn, 'tbl_classes') && app_column_exists($conn, 'tbl_classes', 'cbc_level') && !app_column_exists($conn, 'tbl_classes', 'cbe_level')) {
		try {
			if (DBDriver === 'pgsql') {
				$conn->exec("ALTER TABLE tbl_classes RENAME COLUMN cbc_level TO cbe_level");
			} else {
				$conn->exec("ALTER TABLE tbl_classes CHANGE cbc_level cbe_level varchar(30) DEFAULT NULL");
			}
			app_forget_column_exists_cache('tbl_classes', 'cbc_level');
			app_forget_column_exists_cache('tbl_classes', 'cbe_level');
		} catch (Throwable $e) {
			error_log('[app_migrate_cbc_to_cbe_schema.column] ' . $e->getMessage());
		}
	}

	try {
		if (app_table_exists($conn, 'tbl_exams') && app_column_exists($conn, 'tbl_exams', 'assessment_mode')) {
			$stmt = $conn->prepare("UPDATE tbl_exams SET assessment_mode = 'cbe' WHERE LOWER(COALESCE(assessment_mode, '')) = 'cbc'");
			$stmt->execute();
		}
	} catch (Throwable $e) {
		error_log('[app_migrate_cbc_to_cbe_schema.exams] ' . $e->getMessage());
	}

	try {
		if (app_table_exists($conn, 'tbl_grading_systems') && app_column_exists($conn, 'tbl_grading_systems', 'type')) {
			$stmt = $conn->prepare("UPDATE tbl_grading_systems SET type = 'cbe' WHERE LOWER(COALESCE(type, '')) = 'cbc'");
			$stmt->execute();
			if (app_column_exists($conn, 'tbl_grading_systems', 'name')) {
				$stmt = $conn->prepare("UPDATE tbl_grading_systems SET name = REPLACE(name, 'CBC', 'CBE') WHERE name LIKE '%CBC%'");
				$stmt->execute();
			}
			if (app_column_exists($conn, 'tbl_grading_systems', 'description')) {
				$stmt = $conn->prepare("UPDATE tbl_grading_systems SET description = REPLACE(description, 'CBC', 'CBE') WHERE description LIKE '%CBC%'");
				$stmt->execute();
			}
		}
	} catch (Throwable $e) {
		error_log('[app_migrate_cbc_to_cbe_schema.grading] ' . $e->getMessage());
	}

	try {
		if (app_table_exists($conn, 'tbl_settings')) {
			$nameColumn = app_column_exists($conn, 'tbl_settings', 'setting_name') ? 'setting_name' : (app_column_exists($conn, 'tbl_settings', 'name') ? 'name' : '');
			$valueColumn = app_column_exists($conn, 'tbl_settings', 'setting_value') ? 'setting_value' : (app_column_exists($conn, 'tbl_settings', 'value') ? 'value' : '');
			if ($nameColumn !== '') {
				$stmt = $conn->prepare("UPDATE tbl_settings SET {$nameColumn} = 'cbe_public_ranking_enabled' WHERE {$nameColumn} = 'cbc_public_ranking_enabled'");
				$stmt->execute();
			}
			if ($nameColumn !== '' && $valueColumn !== '') {
				$stmt = $conn->prepare("UPDATE tbl_settings SET {$valueColumn} = REPLACE({$valueColumn}, 'CBC', 'CBE') WHERE {$nameColumn} LIKE '%cbe%' AND {$valueColumn} LIKE '%CBC%'");
				$stmt->execute();
			}
		}
	} catch (Throwable $e) {
		error_log('[app_migrate_cbc_to_cbe_schema.settings] ' . $e->getMessage());
	}

	$done = true;
}

function app_tx_savepoint_begin(PDO $conn, string $prefix = 'sp'): ?string
{
	if (!$conn->inTransaction()) {
		return null;
	}
	$name = preg_replace('/[^a-zA-Z0-9_]/', '_', $prefix.'_'.uniqid('', true));
	if ($name === null || $name === '') {
		return null;
	}
	try {
		$conn->exec("SAVEPOINT {$name}");
		return $name;
	} catch (Throwable $e) {
		return null;
	}
}

function app_tx_savepoint_release(PDO $conn, ?string $name): void
{
	if (!$name || !$conn->inTransaction()) {
		return;
	}
	try {
		$conn->exec("RELEASE SAVEPOINT {$name}");
	} catch (Throwable $e) {
		// best effort only
	}
}

function app_tx_savepoint_rollback(PDO $conn, ?string $name): void
{
	if (!$name || !$conn->inTransaction()) {
		return;
	}
	try {
		$conn->exec("ROLLBACK TO SAVEPOINT {$name}");
	} catch (Throwable $e) {
		// best effort only
	}
	try {
		$conn->exec("RELEASE SAVEPOINT {$name}");
	} catch (Throwable $e) {
		// best effort only
	}
}

function app_audit_log(PDO $conn, string $actorType, string $actorId, string $action, string $entity, string $entityId = '', array $meta = []): void
{
	$savepoint = app_tx_savepoint_begin($conn, 'audit_log');
	try {
		if (session_status() === PHP_SESSION_ACTIVE && !empty($_SESSION['impersonation']) && !empty($_SESSION['impersonation']['active'])) {
			$adminId = (string)($_SESSION['impersonation']['admin_id'] ?? '');
			if ($adminId !== '') {
				$meta['impersonating'] = true;
				$meta['impersonated_actor_type'] = $actorType;
				$meta['impersonated_actor_id'] = $actorId;
				$actorType = 'staff';
				$actorId = $adminId;
			}
		}

		if (!app_table_exists($conn, 'tbl_audit_logs')) {
			app_tx_savepoint_release($conn, $savepoint);
			return;
		}

		$ip = $_SERVER['REMOTE_ADDR'] ?? '';
		$ua = $_SERVER['HTTP_USER_AGENT'] ?? '';
		if (!empty($meta)) {
			$metaJson = json_encode($meta, JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE);
			if ($metaJson !== false && $metaJson !== '[]' && $metaJson !== '{}') {
				$ua = trim($ua . ' | meta=' . $metaJson);
			}
		}
		$stmt = $conn->prepare("INSERT INTO tbl_audit_logs (actor_type, actor_id, action, entity, entity_id, ip, user_agent) VALUES (?,?,?,?,?,?,?)");
		$stmt->execute([$actorType, $actorId, $action, $entity, $entityId, $ip, $ua]);
		app_tx_savepoint_release($conn, $savepoint);
	} catch (Throwable $e) {
		app_tx_savepoint_rollback($conn, $savepoint);
	}
}

