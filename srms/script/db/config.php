		dirname(__DIR__, 3) . '/database/srms_mysql_current_mode_patch.sql',
		getcwd() . '/database/srms_mysql_current_mode_patch.sql',
		getcwd() . '/srms/database/srms_mysql_current_mode_patch.sql',
	];

