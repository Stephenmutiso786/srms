					status varchar(20) NOT NULL DEFAULT 'pending',
					review_state varchar(30) NOT NULL DEFAULT 'pending_review',
					total_fees_balance numeric(12,2) NOT NULL DEFAULT 0,
					students_promoted int NOT NULL DEFAULT 0,
					students_repeated int NOT NULL DEFAULT 0,
					students_exited int NOT NULL DEFAULT 0,
					notes text DEFAULT NULL,
					created_by int DEFAULT NULL,
					created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
					reviewed_by int DEFAULT NULL,
					reviewed_at timestamp DEFAULT NULL,
					executed_by int DEFAULT NULL,
					executed_at timestamp DEFAULT NULL,
					approved_by int DEFAULT NULL,
					approved_at timestamp DEFAULT NULL
				)
			");
		} else {
			$conn->exec("
				CREATE TABLE IF NOT EXISTS tbl_promotion_batches (
					id int NOT NULL AUTO_INCREMENT PRIMARY KEY,
					class_id int NOT NULL,
					academic_year varchar(20) NOT NULL,
					promotion_cycle varchar(50) NOT NULL DEFAULT 'year_end',
					status varchar(20) NOT NULL DEFAULT 'pending',
					review_state varchar(30) NOT NULL DEFAULT 'pending_review',
					total_fees_balance decimal(12,2) NOT NULL DEFAULT 0,
					students_promoted int NOT NULL DEFAULT 0,
					students_repeated int NOT NULL DEFAULT 0,
					students_exited int NOT NULL DEFAULT 0,
