		}
	}

	if (!app_table_exists($conn, 'tbl_promotion_batches')) {
		if ($isPgsql) {
			$conn->exec("
				CREATE TABLE IF NOT EXISTS tbl_promotion_batches (
					id SERIAL PRIMARY KEY,
					class_id int NOT NULL,
