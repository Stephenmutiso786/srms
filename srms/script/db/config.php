function app_sms_token_segments(string $message): int
{
	$message = trim($message);
	if ($message === '') {
		return 0;
	}
	$length = function_exists('mb_strlen') ? mb_strlen($message, 'UTF-8') : strlen($message);
	return max(1, (int)ceil($length / 160));
}

