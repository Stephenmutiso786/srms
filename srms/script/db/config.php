		}
	}

	if (!app_table_exists($conn, 'tbl_student_promotions')) {
		if ($isPgsql) {
			$conn->exec("
				CREATE TABLE IF NOT EXISTS tbl_student_promotions (
					id SERIAL PRIMARY KEY,
					batch_id int NOT NULL,
					student_id varchar(64) NOT NULL,
					from_class int NOT NULL,
					to_class int DEFAULT NULL,
					status varchar(20) NOT NULL DEFAULT 'promoted',
					mean_score numeric(6,2) DEFAULT NULL,
					merit_grade varchar(10) DEFAULT NULL,
					fees_balance numeric(12,2) NOT NULL DEFAULT 0,
					fees_cleared boolean NOT NULL DEFAULT FALSE,
					report_card_finalized boolean NOT NULL DEFAULT FALSE,
					notes text DEFAULT NULL,
					created_by int DEFAULT NULL,
					created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
					suggested_status varchar(20) DEFAULT NULL,
					final_status varchar(20) DEFAULT NULL,
					review_comment text DEFAULT NULL,
					reviewed_by int DEFAULT NULL,
					reviewed_at timestamp DEFAULT NULL,
					override_reason text DEFAULT NULL,
					certificate_generated boolean NOT NULL DEFAULT FALSE
