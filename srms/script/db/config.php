function app_create_promotion_batch(PDO $conn, int $classId, string $academicYear, string $promotionCycle = 'year_end', int $createdBy = 0, string $notes = ''): int
{
	app_ensure_promotion_workflow_schema($conn);

	$academicYear = trim($academicYear);
	$promotionCycle = trim($promotionCycle) !== '' ? trim($promotionCycle) : 'year_end';
	if ($classId < 1 || $academicYear === '') {
		throw new RuntimeException('Missing promotion batch details.');
	}
	if (!preg_match('/^\d{4}(\/\d{4})?$/', $academicYear)) {
		throw new RuntimeException('Invalid academic year format.');
	}

	$stmt = $conn->prepare('SELECT id, name, grade FROM tbl_classes WHERE id = ? LIMIT 1');
	$stmt->execute([$classId]);
	$currentClass = $stmt->fetch(PDO::FETCH_ASSOC);
	if (!$currentClass) {
		throw new RuntimeException('Selected class was not found.');
	}
	$currentGrade = app_effective_grade_level((string)($currentClass['name'] ?? ''), $currentClass['grade'] ?? null);

	$stmt = $conn->prepare('SELECT id FROM tbl_promotion_batches WHERE class_id = ? AND academic_year = ? AND promotion_cycle = ? LIMIT 1');
	$stmt->execute([$classId, $academicYear, $promotionCycle]);
	$existingBatchId = (int)($stmt->fetchColumn() ?: 0);
	if ($existingBatchId > 0) {
		throw new RuntimeException('Promotion batch already exists for this class/year/cycle combination.');
	}

	$rule = app_promotion_rule_for_grade($conn, $currentGrade);
	$needsHeadteacherReview = (bool)($rule['require_headteacher_approval'] ?? true);

	$nextGrade = $currentGrade + 1;
	$nextClassId = $classId;
	if ($nextGrade > 1) {
		$stmt = $conn->prepare('SELECT id, name, grade FROM tbl_classes ORDER BY name');
		$stmt->execute();
		foreach ($stmt->fetchAll(PDO::FETCH_ASSOC) as $classRow) {
			$candidateGrade = app_effective_grade_level((string)($classRow['name'] ?? ''), $classRow['grade'] ?? null);
			if ($candidateGrade === $nextGrade) {
				$nextClassId = (int)$classRow['id'];
				break;
			}
		}
	}

	$batchColumns = ['class_id', 'academic_year', 'promotion_cycle', 'status', 'created_by', 'notes'];
	$batchValues = [$classId, $academicYear, $promotionCycle, 'pending', $createdBy > 0 ? $createdBy : null, $notes];
	if (app_column_exists($conn, 'tbl_promotion_batches', 'review_state')) {
		$batchColumns[] = 'review_state';
		$batchValues[] = $needsHeadteacherReview ? 'pending_review' : 'ready_for_execution';
	}
	$stmt = $conn->prepare('INSERT INTO tbl_promotion_batches (' . implode(', ', $batchColumns) . ') VALUES (' . implode(', ', array_fill(0, count($batchColumns), '?')) . ')');
	$stmt->execute($batchValues);
	$batchId = (int)$conn->lastInsertId();

	$studentStatusFilter = '';
	if (app_column_exists($conn, 'tbl_students', 'status')) {
		$statusType = '';
		if (DBDriver === 'pgsql') {
			$statusTypeStmt = $conn->prepare("SELECT data_type FROM information_schema.columns WHERE table_schema = 'public' AND table_name = 'tbl_students' AND column_name = 'status' LIMIT 1");
			$statusTypeStmt->execute();
			$statusType = strtolower(trim((string)$statusTypeStmt->fetchColumn()));
		} else {
			$statusTypeStmt = $conn->prepare("SELECT data_type FROM information_schema.columns WHERE table_schema = ? AND table_name = 'tbl_students' AND column_name = 'status' LIMIT 1");
			$statusTypeStmt->execute([DBName]);
			$statusType = strtolower(trim((string)$statusTypeStmt->fetchColumn()));
		}
		$studentStatusFilter = in_array($statusType, ['character varying', 'varchar', 'text', 'char'], true)
			? " AND COALESCE(LOWER(TRIM(status)), '') IN ('1', 'active', 'enabled')"
			: ' AND COALESCE(status, 1) = 1';
	}

	$reportMeanExpr = '0';
	$reportFinalizedExpr = 'FALSE';
	$reportGradeExpr = 'NULL';
	if (app_table_exists($conn, 'tbl_report_cards')) {
		$reportMeanColumn = app_column_exists($conn, 'tbl_report_cards', 'mean_score') ? 'mean_score' : (app_column_exists($conn, 'tbl_report_cards', 'mean') ? 'mean' : '');
		if ($reportMeanColumn !== '') {
			$reportMeanExpr = 'COALESCE((SELECT r.' . $reportMeanColumn . ' FROM tbl_report_cards r WHERE r.student_id = st.id ORDER BY r.id DESC LIMIT 1), 0)';
		}
		if (app_column_exists($conn, 'tbl_report_cards', 'grade')) {
			$reportGradeExpr = '(SELECT r.grade FROM tbl_report_cards r WHERE r.student_id = st.id ORDER BY r.id DESC LIMIT 1)';
		}
		if (app_column_exists($conn, 'tbl_report_cards', 'finalized')) {
			$reportFinalizedExpr = 'COALESCE((SELECT r.finalized FROM tbl_report_cards r WHERE r.student_id = st.id ORDER BY r.id DESC LIMIT 1), FALSE)';
		} else {
			$reportFinalizedExpr = 'CASE WHEN EXISTS (SELECT 1 FROM tbl_report_cards r WHERE r.student_id = st.id) THEN TRUE ELSE FALSE END';
		}
	}

	$feesBalanceExpr = '0';
	if (app_table_exists($conn, 'tbl_fees_charged') && app_table_exists($conn, 'tbl_fees_paid')) {
		$feesBalanceExpr = 'COALESCE((SELECT SUM(cf.amount) FROM tbl_fees_charged cf WHERE cf.student_id = st.id), 0) - COALESCE((SELECT SUM(cp.amount) FROM tbl_fees_paid cp WHERE cp.student_id = st.id), 0)';
	} elseif (app_table_exists($conn, 'tbl_invoices') && app_table_exists($conn, 'tbl_invoice_lines')) {
		$feesBalanceExpr = 'COALESCE((SELECT COALESCE(SUM(l.amount), 0) FROM tbl_invoices i INNER JOIN tbl_invoice_lines l ON l.invoice_id = i.id WHERE i.student_id = st.id AND i.status <> \'void\'), 0)';
		if (app_table_exists($conn, 'tbl_payments')) {
			$feesBalanceExpr .= ' - COALESCE((SELECT COALESCE(SUM(p.amount), 0) FROM tbl_invoices i2 INNER JOIN tbl_payments p ON p.invoice_id = i2.id WHERE i2.student_id = st.id AND i2.status <> \'void\'), 0)';
		}
	}

	$stmt = $conn->prepare('
		SELECT st.id, st.fname, st.mname, st.lname,
			   ' . $reportMeanExpr . ' AS mean_score,
			   ' . $reportGradeExpr . ' AS report_grade,
			   ' . $reportFinalizedExpr . ' AS report_finalized,
			   ' . $feesBalanceExpr . ' AS fees_balance
		FROM tbl_students st
		WHERE st.class = ?' . $studentStatusFilter . '
	');
	$stmt->execute([$classId]);
	$studentDetails = $stmt->fetchAll(PDO::FETCH_ASSOC);
	if (empty($studentDetails)) {
		throw new RuntimeException('No active students found in this class.');
	}

	$totalFeesBalance = 0.0;
	foreach ($studentDetails as $student) {
		$meanScore = (float)($student['mean_score'] ?? 0);
		$feesBalance = (float)($student['fees_balance'] ?? 0);
		$reportFinalized = (bool)($student['report_finalized'] ?? false);
		$reportGrade = trim((string)($student['report_grade'] ?? ''));
		$meritGrade = null;
		if ($reportGrade !== '') {
			$meritGrade = $reportGrade;
		} elseif ($meanScore > 0) {
			$classGradingSystemId = app_class_grading_system_id($conn, $classId);
			list($derivedGrade) = report_grade_for_score($conn, $meanScore, $classGradingSystemId);
			$meritGrade = trim((string)$derivedGrade) !== '' ? (string)$derivedGrade : null;
		}

		$feesCleared = $feesBalance <= 0;
		$totalFeesBalance += max(0, $feesBalance);
		$notesLine = [];
		$status = 'promoted';
		if ($meanScore < (float)$rule['min_score_for_promotion']) {
			$status = 'repeated';
		}
		if ((bool)$rule['require_fees_clearance'] && !$feesCleared) {
			$status = 'repeated';
		}
		if ((bool)$rule['require_report_finalization'] && !$reportFinalized) {
			$status = 'repeated';
		}
		if ($status === 'promoted' && $needsHeadteacherReview) {
			$status = 'conditional';
		}

		if ($status === 'repeated') {
			if ($meanScore < (float)$rule['min_score_for_promotion']) {
				$notesLine[] = 'Below minimum score';
			}
			if ((bool)$rule['require_fees_clearance'] && !$feesCleared) {
				$notesLine[] = 'Fees not cleared';
			}
			if ((bool)$rule['require_report_finalization'] && !$reportFinalized) {
				$notesLine[] = 'Report not finalized';
			}
		} elseif ($status === 'conditional') {
			$notesLine[] = 'Recommended for promotion pending review';
			if ($needsHeadteacherReview) {
				$notesLine[] = 'Awaiting headteacher/deputy review';
			}
		}

		$suggestedStatus = $status;
		$finalStatus = $status === 'conditional' ? 'promoted' : $status;
		$promotionColumns = [
			'batch_id', 'student_id', 'from_class', 'to_class', 'status', 'mean_score', 'merit_grade',
			'fees_balance', 'fees_cleared', 'report_card_finalized', 'notes', 'created_by'
		];
		$promotionValues = [
			$batchId,
			(string)$student['id'],
			$classId,
			($status === 'promoted' || $status === 'conditional') ? $nextClassId : $classId,
			$suggestedStatus,
			$meanScore,
			$meritGrade,
			$feesBalance,
			$feesCleared,
			$reportFinalized,
			implode('; ', $notesLine),
			$createdBy > 0 ? $createdBy : null,
		];
		if (app_column_exists($conn, 'tbl_student_promotions', 'suggested_status')) {
			$promotionColumns[] = 'suggested_status';
			$promotionValues[] = $suggestedStatus;
		}
		if (app_column_exists($conn, 'tbl_student_promotions', 'final_status')) {
			$promotionColumns[] = 'final_status';
			$promotionValues[] = $finalStatus;
		}

		$stmt = $conn->prepare('INSERT INTO tbl_student_promotions (' . implode(', ', $promotionColumns) . ') VALUES (' . implode(', ', array_fill(0, count($promotionColumns), '?')) . ')');
		$stmt->execute($promotionValues);
	}

	$stmt = $conn->prepare('UPDATE tbl_promotion_batches SET total_fees_balance = ? WHERE id = ?');
	$stmt->execute([round($totalFeesBalance, 2), $batchId]);

	return $batchId;
}

function app_auto_prepare_year_end_promotions(PDO $conn, int $createdBy = 0): array
{
	$summary = [
		'ran' => false,
		'eligible' => false,
		'already_generated' => false,
		'academic_year' => '',
		'created_batches' => 0,
		'existing_batches' => 0,
		'skipped_classes' => 0,
		'batch_ids' => [],
		'message' => '',
	];

	app_ensure_promotion_workflow_schema($conn);
	$settings = app_promotion_settings($conn);
	$sessionEndDate = trim(app_setting_get($conn, 'session_end_date', ''));
	$academicYear = trim(app_setting_get($conn, 'current_academic_year', date('Y')));
	$summary['academic_year'] = $academicYear;

	if ($settings['auto_promotion_enabled'] !== '1') {
		$summary['message'] = 'Auto promotion is disabled.';
		return $summary;
	}
	if ($sessionEndDate === '') {
		$summary['message'] = 'Session end date is not set.';
		return $summary;
	}
	$today = strtotime(date('Y-m-d'));
	$endDate = strtotime($sessionEndDate);
	if ($endDate === false || $today === false || $today < $endDate) {
		$summary['message'] = 'Academic year has not ended yet.';
		return $summary;
	}

	$summary['eligible'] = true;
	if (trim((string)$settings['promotion_auto_last_generated_year']) === $academicYear) {
		$summary['already_generated'] = true;
		$summary['message'] = 'Promotion batches were already auto-generated for this academic year.';
		return $summary;
	}

	$startedTransaction = false;
	try {
		if (!$conn->inTransaction()) {
			$conn->beginTransaction();
			$startedTransaction = true;
		}

		$studentStatusFilter = '';
		if (app_column_exists($conn, 'tbl_students', 'status')) {
			$statusType = '';
			if (DBDriver === 'pgsql') {
				$statusTypeStmt = $conn->prepare("SELECT data_type FROM information_schema.columns WHERE table_schema = 'public' AND table_name = 'tbl_students' AND column_name = 'status' LIMIT 1");
				$statusTypeStmt->execute();
				$statusType = strtolower(trim((string)$statusTypeStmt->fetchColumn()));
			} else {
				$statusTypeStmt = $conn->prepare("SELECT data_type FROM information_schema.columns WHERE table_schema = ? AND table_name = 'tbl_students' AND column_name = 'status' LIMIT 1");
				$statusTypeStmt->execute([DBName]);
				$statusType = strtolower(trim((string)$statusTypeStmt->fetchColumn()));
			}
			$studentStatusFilter = in_array($statusType, ['character varying', 'varchar', 'text', 'char'], true)
				? " WHERE COALESCE(LOWER(TRIM(status)), '') IN ('1', 'active', 'enabled')"
				: ' WHERE COALESCE(status, 1) = 1';
		}
		$studentClassColumn = app_column_exists($conn, 'tbl_students', 'class_id') ? 'class_id' : 'class';
		$stmt = $conn->prepare('SELECT c.id, c.name, c.grade, COUNT(st.id) AS student_count
			FROM tbl_classes c
			INNER JOIN tbl_students st ON st.' . $studentClassColumn . ' = c.id' . $studentStatusFilter . '
			GROUP BY c.id, c.name, c.grade
			ORDER BY c.id');
		$stmt->execute();
		$classRows = $stmt->fetchAll(PDO::FETCH_ASSOC);

		foreach ($classRows as $classRow) {
			$classId = (int)($classRow['id'] ?? 0);
			if ($classId < 1 || (int)($classRow['student_count'] ?? 0) < 1) {
				$summary['skipped_classes']++;
				continue;
			}
			$existingStmt = $conn->prepare('SELECT id FROM tbl_promotion_batches WHERE class_id = ? AND academic_year = ? AND promotion_cycle = ? LIMIT 1');
			$existingStmt->execute([$classId, $academicYear, 'year_end']);
			$existingBatchId = (int)($existingStmt->fetchColumn() ?: 0);
			if ($existingBatchId > 0) {
				$summary['existing_batches']++;
				$summary['batch_ids'][] = $existingBatchId;
				continue;
			}
			$note = 'Auto-generated after academic year end date ' . $sessionEndDate . '.';
			try {
				$newBatchId = app_create_promotion_batch($conn, $classId, $academicYear, 'year_end', $createdBy, $note);
				$summary['created_batches']++;
				$summary['batch_ids'][] = $newBatchId;
				if ($createdBy > 0) {
					app_audit_log($conn, 'staff', (string)$createdBy, 'promotion.batch.auto_generate', 'tbl_promotion_batches', (string)$newBatchId, ['class_id' => $classId, 'academic_year' => $academicYear]);
				}
			} catch (Throwable $e) {
				$summary['skipped_classes']++;
			}
		}

		app_setting_set($conn, 'promotion_auto_last_generated_year', $academicYear, $createdBy > 0 ? $createdBy : null, false);
		app_setting_set($conn, 'promotion_auto_last_generated_at', date('Y-m-d H:i:s'), $createdBy > 0 ? $createdBy : null, false);
		if ($startedTransaction && $conn->inTransaction()) {
			$conn->commit();
		}
		$summary['ran'] = true;
		$summary['message'] = $summary['created_batches'] > 0
			? 'Auto-generated ' . $summary['created_batches'] . ' promotion batch(es).'
			: 'No new promotion batches were created.';
		return $summary;
	} catch (Throwable $e) {
		if ($startedTransaction && $conn->inTransaction()) {
			$conn->rollBack();
		}
		$summary['message'] = 'Auto promotion failed: ' . $e->getMessage();
		return $summary;
	}
}

