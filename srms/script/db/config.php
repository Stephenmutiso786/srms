					status varchar(20) NOT NULL DEFAULT 'promoted',
					mean_score decimal(6,2) DEFAULT NULL,
					merit_grade varchar(10) DEFAULT NULL,
					fees_balance decimal(12,2) NOT NULL DEFAULT 0,
					fees_cleared tinyint(1) NOT NULL DEFAULT 0,
					report_card_finalized tinyint(1) NOT NULL DEFAULT 0,
					notes text DEFAULT NULL,
					created_by int DEFAULT NULL,
					created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
					suggested_status varchar(20) DEFAULT NULL,
					final_status varchar(20) DEFAULT NULL,
