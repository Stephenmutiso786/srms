function app_impersonation_session_by_impersonated_key(PDO $conn, string $sessionKey): ?array
{
	if ($sessionKey === '') {
		return null;
	}
	if (!app_table_exists($conn, 'tbl_impersonation_sessions')) {
		return null;
	}
	$stmt = $conn->prepare("SELECT i.*, s.fname AS admin_fname, s.lname AS admin_lname
		FROM tbl_impersonation_sessions i
		LEFT JOIN tbl_staff s ON s.id = i.admin_staff_id
		WHERE i.impersonated_session_key = ?
		AND COALESCE(i.is_active, 1) = 1
		AND i.ended_at IS NULL
		ORDER BY i.id DESC
		LIMIT 1");
	$stmt->execute([$sessionKey]);
	$row = $stmt->fetch(PDO::FETCH_ASSOC);
	if (!$row) {
		return null;
	}
	return $row;
}

