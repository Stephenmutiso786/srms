function app_normalize_ip_address(string $ip): string
{
	$ip = trim(strtolower($ip));
	if ($ip === '') {
		return '';
	}

	if (strpos($ip, ',') !== false) {
		$parts = array_values(array_filter(array_map('trim', explode(',', $ip))));
		$ip = strtolower((string)($parts[0] ?? ''));
	}

	if ($ip === '::1') {
		return '127.0.0.1';
	}

	if (strpos($ip, '::ffff:') === 0) {
		$mapped = substr($ip, 7);
		if (filter_var($mapped, FILTER_VALIDATE_IP, FILTER_FLAG_IPV4)) {
			return $mapped;
		}
	}

	return $ip;
}

function app_request_client_ip(): string
{
	$candidates = [
		(string)($_SERVER['HTTP_X_FORWARDED_FOR'] ?? ''),
		(string)($_SERVER['HTTP_X_REAL_IP'] ?? ''),
		(string)($_SERVER['REMOTE_ADDR'] ?? ''),
	];

	foreach ($candidates as $candidate) {
		$ip = app_normalize_ip_address($candidate);
		if ($ip !== '') {
			return $ip;
		}
	}

	return '';
}

function app_session_ip_matches(string $storedIp, string $currentIp): bool
{
	$storedIp = app_normalize_ip_address($storedIp);
	$currentIp = app_normalize_ip_address($currentIp);

	if ($storedIp === '' || $currentIp === '') {
		return true;
	}

	return $storedIp === $currentIp;
}

function app_session_enforce_ip(): bool
{
	$raw = strtolower(trim((string)(getenv('SESSION_STRICT_IP') ?: '')));
	if ($raw !== '') {
		return !in_array($raw, ['0', 'false', 'no', 'off'], true);
	}
	return !app_request_is_api();
}

function app_issue_auth_cookies(string $level, string $sessionId, bool $crossSite = false, int $minutes = 4320): void
{
	$expires = time() + (60 * max(1, $minutes));
	$options = [
		'expires' => $expires,
		'path' => '/',
		'secure' => app_cookie_secure(),
		'httponly' => true,
		'samesite' => $crossSite ? 'None' : 'Lax',
	];
	if ($crossSite && !$options['secure']) {
		$options['secure'] = true;
	}
	setcookie('__SRMS__logged', (string)$level, $options);
	setcookie('__SRMS__key', (string)$sessionId, $options);
}

function app_clear_auth_cookies(bool $crossSite = false): void
{
	$options = [
		'expires' => time() - 3600,
		'path' => '/',
		'secure' => app_cookie_secure() || $crossSite,
		'httponly' => true,
		'samesite' => $crossSite ? 'None' : 'Lax',
	];
	setcookie('__SRMS__logged', '', $options);
	setcookie('__SRMS__key', '', $options);
