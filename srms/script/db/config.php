function app_promotion_rule_for_grade(PDO $conn, int $gradeLevel): array
{
	$rule = [
		'grade_level' => $gradeLevel,
		'min_score_for_promotion' => 40.0,
		'require_fees_clearance' => true,
		'require_report_finalization' => true,
		'require_headteacher_approval' => true,
		'auto_generate_certificate' => false,
		'certificate_type' => 'general',
	];

	if ($gradeLevel < 1 || !app_table_exists($conn, 'tbl_promotion_rules')) {
		return $rule;
	}

	$stmt = $conn->prepare('SELECT grade_level, min_score_for_promotion, require_fees_clearance, require_report_finalization, require_headteacher_approval, auto_generate_certificate, certificate_type
		FROM tbl_promotion_rules
		WHERE school_id IS NULL AND grade_level = ?
		LIMIT 1');
	$stmt->execute([$gradeLevel]);
	$row = $stmt->fetch(PDO::FETCH_ASSOC);
	if (!$row) {
		return $rule;
	}

	$rule['grade_level'] = (int)($row['grade_level'] ?? $gradeLevel);
	$rule['min_score_for_promotion'] = (float)($row['min_score_for_promotion'] ?? $rule['min_score_for_promotion']);
	$rule['require_fees_clearance'] = (bool)($row['require_fees_clearance'] ?? $rule['require_fees_clearance']);
	$rule['require_report_finalization'] = (bool)($row['require_report_finalization'] ?? $rule['require_report_finalization']);
	$rule['require_headteacher_approval'] = (bool)($row['require_headteacher_approval'] ?? $rule['require_headteacher_approval']);
	$rule['auto_generate_certificate'] = (bool)($row['auto_generate_certificate'] ?? $rule['auto_generate_certificate']);
	$rule['certificate_type'] = trim((string)($row['certificate_type'] ?? $rule['certificate_type'])) ?: $rule['certificate_type'];

	return $rule;
}

function app_ensure_promotion_workflow_schema(PDO $conn): void
{
	$isPgsql = DBDriver === 'pgsql';

	if (app_table_exists($conn, 'tbl_classes') && !app_column_exists($conn, 'tbl_classes', 'grade')) {
		$conn->exec("ALTER TABLE tbl_classes ADD COLUMN grade int DEFAULT NULL");
		try {
			$stmt = $conn->prepare("SELECT id, name FROM tbl_classes ORDER BY id ASC");
			$stmt->execute();
			$classes = $stmt->fetchAll(PDO::FETCH_ASSOC);
			$update = $conn->prepare("UPDATE tbl_classes SET grade = ? WHERE id = ?");
			$fallbackGrade = 1;
			foreach ($classes as $classRow) {
				$name = trim((string)($classRow['name'] ?? ''));
				$grade = 0;
				if ($name !== '' && preg_match('/(\d{1,2})/', $name, $matches)) {
					$grade = (int)$matches[1];
				}
				if ($grade < 1) {
					$grade = $fallbackGrade;
				}
				$update->execute([$grade, (int)$classRow['id']]);
				$fallbackGrade++;
			}
		} catch (Throwable $e) {
			$conn->exec("UPDATE tbl_classes SET grade = id WHERE grade IS NULL OR grade < 1");
		}
	}

	if (app_table_exists($conn, 'tbl_students') && !app_column_exists($conn, 'tbl_students', 'school_id')) {
		$conn->exec("ALTER TABLE tbl_students ADD COLUMN school_id varchar(50) DEFAULT NULL");
		try {
			$stmt = $conn->prepare("SELECT id FROM tbl_students WHERE school_id IS NULL OR school_id = '' ORDER BY id ASC");
			$stmt->execute();
			$update = $conn->prepare("UPDATE tbl_students SET school_id = ? WHERE id = ?");
			foreach ($stmt->fetchAll(PDO::FETCH_COLUMN) as $studentId) {
				$schoolId = app_generate_school_id($conn, 'STD', (int)date('Y'), 'tbl_students');
				$update->execute([$schoolId, (string)$studentId]);
			}
		} catch (Throwable $e) {
			// Best effort only.
		}
	}

	if (app_table_exists($conn, 'tbl_staff') && !app_column_exists($conn, 'tbl_staff', 'school_id')) {
		$conn->exec("ALTER TABLE tbl_staff ADD COLUMN school_id varchar(50) DEFAULT NULL");
		try {
			$stmt = $conn->prepare("SELECT id, level FROM tbl_staff WHERE school_id IS NULL OR school_id = '' ORDER BY id ASC");
			$stmt->execute();
			$rows = $stmt->fetchAll(PDO::FETCH_ASSOC);
			$update = $conn->prepare("UPDATE tbl_staff SET school_id = ? WHERE id = ?");
			foreach ($rows as $staffRow) {
				$prefix = app_staff_prefix((string)($staffRow['level'] ?? ''));
				$schoolId = app_generate_school_id($conn, $prefix, (int)date('Y'), 'tbl_staff');
				$update->execute([$schoolId, (int)$staffRow['id']]);
			}
		} catch (Throwable $e) {
			// Best effort only.
		}
	}

	if (!app_table_exists($conn, 'tbl_promotion_rules')) {
		if ($isPgsql) {
			$conn->exec("
				CREATE TABLE IF NOT EXISTS tbl_promotion_rules (
					id SERIAL PRIMARY KEY,
					school_id int DEFAULT NULL,
					grade_level int NOT NULL,
					min_score_for_promotion numeric(5,2) NOT NULL DEFAULT 40,
					require_fees_clearance boolean NOT NULL DEFAULT TRUE,
