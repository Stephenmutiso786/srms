function app_impersonation_blocks_current_request(): bool
{
	if (strtoupper((string)($_SERVER['REQUEST_METHOD'] ?? 'GET')) !== 'POST') {
		return false;
	}
	$path = strtolower((string)(parse_url((string)($_SERVER['REQUEST_URI'] ?? ''), PHP_URL_PATH) ?? ''));
	if ($path === '') {
		return false;
	}
	$blockedTokens = [
		'change_password',
		'reset_password',
		'update_profile',
		'bulk_delete',
		'drop_user',
		'drop_student',
		'drop_parent',
		'assign_role',
		'new_role',
		'save_role',
		'update_user_role',
		'save_user_roles',
		'update_user2',
		'new_user2',
		'new_parent',
	];
	foreach ($blockedTokens as $token) {
		if (strpos($path, $token) !== false) {
			return true;
		}
	}
	return false;
}

function app_generate_school_id(PDO $conn, string $prefix, int $year, string $table): string
{
	$prefix = strtoupper(trim($prefix));
	$year = $year > 0 ? $year : (int)date('Y');
	$like = $prefix.'-'.$year.'-%';

	do {
		$stmt = $conn->prepare("SELECT COUNT(*) FROM {$table} WHERE school_id LIKE ?");
		$stmt->execute([$like]);
		$count = (int)$stmt->fetchColumn();
		$number = $count + 1;
		$schoolId = sprintf('%s-%d-%04d', $prefix, $year, $number);

		$stmt = $conn->prepare("SELECT 1 FROM {$table} WHERE school_id = ? LIMIT 1");
		$stmt->execute([$schoolId]);
		$exists = $stmt->fetchColumn();
	} while ($exists);

	return $schoolId;
}

