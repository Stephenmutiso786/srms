function app_role_from_level(int $level): string
{
	if ($level === 3) { return 'student'; }
	if ($level === 4) { return 'parent'; }
	if ($level === 2) { return 'teacher'; }
	if ($level === 0) { return 'admin'; }
	if ($level === 1) { return 'admin'; }
	if ($level === 5) { return 'accountant'; }
	return 'staff';
}

function app_ensure_edubot_memory_table(PDO $conn): void
{
	if (app_table_exists($conn, 'tbl_edubot_memory')) {
		return;
	}

	if (DBDriver === 'pgsql') {
		$conn->exec("CREATE TABLE IF NOT EXISTS tbl_edubot_memory (
			id integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
			actor_type varchar(20) NOT NULL,
			actor_id varchar(50) NOT NULL,
			role varchar(20) NOT NULL,
			intent varchar(50) NOT NULL DEFAULT 'general',
			message text NOT NULL,
			response text NOT NULL,
			created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
			PRIMARY KEY (id)
		)");
		$conn->exec("CREATE INDEX IF NOT EXISTS tbl_edubot_memory_actor_idx ON tbl_edubot_memory (actor_type, actor_id, id DESC)");
		return;
	}

	$conn->exec("CREATE TABLE IF NOT EXISTS tbl_edubot_memory (
		id int NOT NULL AUTO_INCREMENT,
		actor_type varchar(20) NOT NULL,
		actor_id varchar(50) NOT NULL,
		role varchar(20) NOT NULL,
		intent varchar(50) NOT NULL DEFAULT 'general',
		message text NOT NULL,
		response text NOT NULL,
		created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
		PRIMARY KEY (id),
		KEY tbl_edubot_memory_actor_idx (actor_type, actor_id, id)
	) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4");
}

function app_edubot_history_text(PDO $conn, string $actorType, string $actorId, int $limit = 8): string
{
	$history = app_ai_history($conn, $actorType, $actorId, $limit);
	if (empty($history)) {
		return '';
	}

	$lines = [];
	foreach ($history as $item) {
		$role = strtoupper((string)($item['role'] ?? 'user'));
		$text = trim((string)($item['text'] ?? ''));
		if ($text !== '') {
			$lines[] = $role . ': ' . $text;
		}
	}

	return implode("\n", $lines);
}

